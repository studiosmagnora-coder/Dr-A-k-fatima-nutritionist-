export function WashiTape({
  tone = 'blush',
  className = '',
}: {
  tone?: 'blush' | 'gold' | 'sage';
  className?: string;
}) {
  const toneClasses =
    tone === 'gold'
      ? 'bg-[#C6A36B]/25 border-[#C6A36B]/30'
      : tone === 'sage'
        ? 'bg-[#A8B5A0]/28 border-[#A8B5A0]/35'
        : 'bg-[#E8C1C8]/65 border-[#C77D8A]/25';

  return (
    <span
      aria-hidden="true"
      className={`washi-tape pointer-events-none inline-block h-5 w-20 border-x border-dashed ${toneClasses} ${className}`}
    />
  );
}

export function PolaroidFrame({
  children,
  caption,
  tilt = 'left',
  tapeTone = 'blush',
}: {
  children: ReactNode;
  caption: string;
  tilt?: 'left' | 'right';
  tapeTone?: 'blush' | 'gold' | 'sage';
}) {
  const tiltClass =
    tilt === 'left'
      ? 'lg:-rotate-1.5 hover:rotate-0'
      : 'lg:rotate-1.5 hover:rotate-0';

  return (
    <div
      className={`relative h-full rounded-2xl border border-[#C6A36B]/28 bg-white p-3 pb-12 shadow-[0_18px_40px_-16px_rgba(73,52,60,0.24)] transition-transform duration-300 sm:p-4 sm:pb-14 ${tiltClass}`}
    >
      <WashiTape
        tone={tapeTone}
        className="absolute -top-2.5 left-1/2 z-10 -translate-x-1/2 -rotate-2"
      />
      <div className="relative h-full min-h-[340px] overflow-hidden rounded-xl border border-[#C77D8A]/12 bg-[#F8E9EB]/35">
        {children}
      </div>
      <p className="font-script pointer-events-none absolute right-4 bottom-2.5 left-4 text-center text-xl tracking-wide text-[#49343C]/90 sm:bottom-3 sm:text-2xl">
        {caption}
      </p>
    </div>
  );
}
